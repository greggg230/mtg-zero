"""Build docs/rulings.md, the M8d rulings tracking doc (ENGINE.md 15, 37).

Inputs:
  data/rulings/powerlsv.rulings.json  the rulings (tools/fetch_rulings.py)
  data/rulings/triage.tsv             one row per distinct ruling text, keyed by
                                      the first 8 hex digits of its SHA-1:
                                      class (a testable here, b not applicable,
                                      c not reachable in the cube), area or
                                      reason code, a note
  engine/tests/*.rs                   `// ruling: <hash8> ...` comments inside
                                      test functions; `#[ignore = "RULING: ..."]`
                                      marks a deferred one (an engine bug left)
  data/rulings/deferred.tsv           (optional) hash8, diagnosis

A ruling with a test is class a whatever the triage says (the doc flags it).
Fails loudly on a marker naming an unknown ruling.

    python tools/rulings_doc.py [--check]   (--check: exit 1 if the doc changes)
"""

import glob
import hashlib
import json
import os
import re
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RULINGS = os.path.join(ROOT, "data", "rulings", "powerlsv.rulings.json")
TRIAGE = os.path.join(ROOT, "data", "rulings", "triage.tsv")
DEFERRED = os.path.join(ROOT, "data", "rulings", "deferred.tsv")
TESTS = os.path.join(ROOT, "engine", "tests")
OUT = os.path.join(ROOT, "docs", "rulings.md")

CODES = {
    "MP": "multiplayer",
    "CMD": "Commander",
    "TRN": "tournament / deck construction",
    "PRINT": "printing, wording, reminder text",
    "DEF": "a definition, no behaviour of its own",
    "NR": "not reachable with the cube's cards",
}


def h8(text):
    return hashlib.sha1(text.encode()).hexdigest()[:8]


def scan_tests():
    """hash8 -> [(file, fn, ignored)]"""
    found = defaultdict(list)
    for path in sorted(glob.glob(os.path.join(TESTS, "*.rs"))):
        name = os.path.basename(path)[:-3]
        lines = open(path, encoding="utf-8").read().split("\n")
        fn, ignored, pending_ignore = None, False, False
        for line in lines:
            s = line.strip()
            if s.startswith("#[ignore"):
                pending_ignore = True
            m = re.match(r"(?:pub )?fn (\w+)\(", s)
            if m:
                fn, ignored, pending_ignore = m.group(1), pending_ignore, False
            m = re.match(r"// ruling: ((?:[0-9a-f]{8} ?)+)$", s)
            if m and fn:
                for h in m.group(1).split():
                    found[h].append((name, fn, ignored))
    return found


def main():
    rulings = json.load(open(RULINGS, encoding="utf-8"))
    triage = {}
    for line in open(TRIAGE, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        h, cls, code, note = line.rstrip("\n").split("\t")
        triage[h] = (cls, code, note)
    deferred = {}
    if os.path.exists(DEFERRED):
        for line in open(DEFERRED, encoding="utf-8"):
            if line.strip() and not line.startswith("#"):
                h, why = line.rstrip("\n").split("\t", 1)
                deferred[h] = why
    tests = scan_tests()
    known = {h8(r["text"]) for c in rulings for r in c["rulings"]}
    unknown = sorted(set(tests) - known)
    if unknown:
        sys.exit(f"test markers name unknown rulings: {unknown}")
    missing = sorted(known - set(triage))
    if missing:
        sys.exit(f"rulings missing from triage.tsv: {missing[:10]} ({len(missing)})")

    # Per ruling instance (a card's ruling) and per distinct text.
    inst = Counter()
    distinct = {}
    rows = []
    for c in rulings:
        for r in c["rulings"]:
            h = h8(r["text"])
            cls, code, note = triage[h]
            t = tests.get(h, [])
            flag = ""
            if t and cls != "a":
                flag = f" (triaged {cls} {code}; tested)"
                cls, code = "a", "tested"
            if not t:
                status = "untested" if cls == "a" else "-"
            elif all(ig for (_, _, ig) in t):
                status = "deferred"
            else:
                status = "tested"
            inst[(cls, status)] += 1
            distinct[h] = (cls, status)
            rows.append((c["name"], h, cls, code, note + flag, t, status))
    dcount = Counter(distinct.values())

    def n(counter, cls=None, status=None):
        return sum(v for (k_cls, k_st), v in counter.items() if (cls is None or k_cls == cls) and (status is None or k_st == status))

    out = []
    w = out.append
    w("# The cube's official rulings (M8d)")
    w("")
    w("Generated by `tools/rulings_doc.py` from `data/rulings/powerlsv.rulings.json` (Scryfall, `tools/fetch_rulings.py`),")
    w("`data/rulings/triage.tsv` and the `// ruling: <hash>` comments of the engine tests; do not edit by hand.")
    w("ENGINE.md 15 lists the suites, 37 what they found.")
    w("")
    w("Classes: **a** testable game-rules behaviour in this engine's two-player cube games; **b** not applicable")
    w("(" + ", ".join(f"{k} {v}" for k, v in CODES.items() if k != "NR") + "); **c** about a mechanic or situation")
    w("no cube card reaches (NR). An `a` ruling's area is where its test belongs (`engine/tests/rulings_<area>.rs`")
    w("or an existing suite). Status: `tested` (a passing test names it), `deferred` (only `#[ignore]`d tests: an engine")
    w("bug left, below), `untested` (class a, no test yet: part 2's work).")
    w("")
    w("## Coverage")
    w("")
    w("| | rulings (card, ruling) | distinct texts |")
    w("|---|---:|---:|")
    w(f"| fetched | {sum(inst.values())} | {len(distinct)} |")
    w(f"| class a | {n(inst, 'a')} | {n(dcount, 'a')} |")
    w(f"| class b | {n(inst, 'b')} | {n(dcount, 'b')} |")
    w(f"| class c | {n(inst, 'c')} | {n(dcount, 'c')} |")
    w(f"| a, tested (passing) | {n(inst, 'a', 'tested')} | {n(dcount, 'a', 'tested')} |")
    w(f"| a, deferred | {n(inst, 'a', 'deferred')} | {n(dcount, 'a', 'deferred')} |")
    w(f"| a, untested | {n(inst, 'a', 'untested')} | {n(dcount, 'a', 'untested')} |")
    w("")
    areas = Counter()
    areas_tested = Counter()
    for h, (cls, status) in distinct.items():
        if cls == "a":
            a = triage[h][1] if triage[h][0] == "a" else "tested"
            areas[a] += 1
            if status == "tested":
                areas_tested[a] += 1
    w("Class a by area (distinct texts): " + ", ".join(f"{a} {areas_tested[a]}/{areas[a]}" for a, _ in areas.most_common()) + " (tested/all).")
    w("")
    if deferred:
        w("## Deferred (engine bugs left)")
        w("")
        for h, why in sorted(deferred.items()):
            w(f"- `{h}`: {why}")
        w("")
    w("## Per card")
    w("")
    w("Hash: the first 8 hex digits of the SHA-1 of the ruling's text (the full text is in the JSON).")
    w("")
    cur = None
    for name, h, cls, code, note, t, status in rows:
        if name != cur:
            cur = name
            w("")
            w(f"### {name}")
            w("")
            w("| ruling | class | area / reason | point | test |")
            w("|---|---|---|---|---|")
        if t:
            test = "; ".join(f"`{f}::{fn}`" + (" (ignored)" if ig else "") for f, fn, ig in t)
        else:
            test = status if cls == "a" else CODES.get(code, code)
        note = note.replace("|", "/")
        w(f"| `{h}` | {cls} | {code} | {note} | {test} |")
    no_rulings = [c["name"] for c in rulings if not c["rulings"]]
    w("")
    w(f"## Cards without rulings ({len(no_rulings)})")
    w("")
    w(", ".join(no_rulings))
    w("")
    text = "\n".join(out)
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if old == text else "docs/rulings.md is out of date")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(
        f"{sum(inst.values())} rulings ({len(distinct)} distinct): a {n(inst, 'a')}, b {n(inst, 'b')}, c {n(inst, 'c')}; "
        f"tested {n(inst, 'a', 'tested')} ({n(dcount, 'a', 'tested')} distinct), deferred {n(inst, 'a', 'deferred')}, "
        f"untested {n(inst, 'a', 'untested')} -> {OUT}"
    )


if __name__ == "__main__":
    main()
